import { expect, test } from '@playwright/test';

test('log a season crossing, retain failed drafts, rewatch, undo, and persist after reload', async ({ page, request }) => {
  test.skip(!test.info().config.metadata.isolatedWatchHistory, 'Run with tests/support/watch-history.config.ts and synthetic accounts.');
  await page.addInitScript(() => localStorage.setItem('backlog:tourSeen', 'true'));
  await page.goto('/');
  await expect(page.locator('.boot-signed-out')).toHaveCount(0);
  await page.getByRole('textbox', { name: /email/i }).fill('reviewer@example.test');
  await page.getByLabel('Password', { exact: true }).fill('review-only');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('button', { name: 'Watched tonight', exact: true }).click();
  await page.getByLabel('Show', { exact: true }).selectOption('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa');
  await expect(page.getByText('Up next · S1 E4', { exact: true })).toBeVisible();
  await page.getByLabel('Episodes watched', { exact: true }).fill('2');
  await page.getByLabel('Watched on', { exact: true }).fill('2026-10-15');
  await expect(page.getByText('S1 E4 → S2 E1', { exact: true })).toBeVisible();
  await request.post('http://127.0.0.1:3101/__review/fail-next');
  await page.getByRole('button', { name: 'Log 2 episodes', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Your choices are still here' })).toBeVisible();
  await expect(page.getByLabel('Episodes watched', { exact: true })).toHaveValue('2');
  await expect(page.getByLabel('Watched on', { exact: true })).toHaveValue('2026-10-15');
  await page.getByRole('button', { name: 'Log 2 episodes', exact: true }).click();
  await expect(page.getByText('Up next · S2 E2', { exact: true })).toBeVisible();
  await expect(page.getByText('15 Oct 2026 · 2 episodes')).toBeVisible();
  await page.getByLabel('Rewatch', { exact: true }).check();
  await page.getByLabel('Choose an episode', { exact: true }).selectOption('1');
  await page.getByRole('button', { name: 'Log rewatch', exact: true }).click();
  await expect(page.getByText('S1 E1 · Rewatch', { exact: true })).toBeVisible();
  await expect(page.getByText('Up next · S2 E2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Undo latest watch log' }).click();
  await expect(page.getByText('S1 E1 · Rewatch', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close watched tonight' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Watched tonight', exact: true }).click();
  await page.getByLabel('Show', { exact: true }).selectOption('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa');
  await expect(page.getByText('Up next · S2 E2', { exact: true })).toBeVisible();
  await expect(page.getByText('15 Oct 2026 · 2 episodes')).toBeVisible();
  await page.getByRole('button', { name: 'Undo latest watch log' }).click();
  await expect(page.getByText('Up next · S1 E4', { exact: true })).toBeVisible();
  await expect(page.getByText('Existing progress has no recorded watch dates.', { exact: false })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.getByRole('dialog', { name: 'Watched tonight', exact: true }).evaluate((element) => element.getBoundingClientRect().top)).toBeLessThan(70);
  await expect(page.getByRole('button', { name: 'Log 1 episode', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Log 1 episode', exact: true }).scrollIntoViewIfNeeded();
  await expect(page.getByRole('button', { name: 'Log 1 episode', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '/private/tmp/backlog-watch-tonight-mobile.png' });
  await page.getByRole('button', { name: 'Close watched tonight' }).click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Add one episode watched for Review Series', exact: true }).click();
  await page.getByRole('button', { name: 'Open Review Series', exact: true }).click();
  await expect(page.getByText('Up next · S2 E1', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Log 1 episode', exact: true }).click();
  await expect(page.getByText('Up next · S2 E2', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Total episodes watched', { exact: true })).toHaveValue('5');
  await page.getByLabel('Total episodes watched', { exact: true }).fill('6');
  await expect(page.getByRole('button', { name: 'Log 1 episode', exact: true })).toBeDisabled();
  await expect(page.getByText('Save or discard your other edits before logging episodes.')).toBeVisible();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('button', { name: 'Open Review Series', exact: true }).click();
  await expect(page.getByText('Up next · S2 E3', { exact: true })).toBeVisible();
});
